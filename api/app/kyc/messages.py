def local_fix(check_id: str, severity: str, args: dict, lang: str) -> str:
    lang = lang if lang in DOCS else "en"
    key = BY_CHECK.get(check_id) or BY_CHECK.get(check_id.rsplit(".", 1)[-1])
    if severity == "review" or not key:
        key = "review"
    doc = DOCS[lang].get(args.get("doc") or check_id.split(".", 1)[0], "")
    return FIX[key][lang].format(doc=doc, age=args.get("age_days", ""))
